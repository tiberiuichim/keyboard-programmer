#!/usr/bin/env python3
"""Regenerate tools/keytables.py from an upstream ch57x-keyboard-tool checkout.

The key/media name -> code tables are the single most error-prone thing to
hand-copy, so they are generated from upstream's Rust enums instead.

    ./pad build                      # creates build/src/ch57x
    python3 tools/gen-keytables.py   # rewrites tools/keytables.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.join(HERE, "..", "build", "src", "ch57x", "src", "keyboard", "mod.rs")
OUT = os.path.join(HERE, "keytables.py")


def block(src, name):
    i = src.index("pub enum %s {" % name)
    return src[src.index("{", i):src.index("\n}\n", i)]


def parse_enum(src, name, start):
    """Parse a strum EnumString enum into {lowercase_name: value}.

    Handles: implicit sequential values, explicit `= 0x123`, aliases written as
    #[strum(serialize="x", serialize="y")] either inline or on their own line.
    """
    val, out, pending = start, {}, []
    for raw in block(src, name).splitlines()[1:]:
        ln = raw.strip()
        if not ln or ln.startswith("//"):
            continue
        aliases = re.findall(r'serialize="([^"]+)"', ln)
        ln = re.sub(r"#\[strum\([^\]]*\)\]", "", ln).strip()
        if not ln:                                   # attribute-only line
            pending += aliases
            continue
        m = re.match(r"^(\w+)\s*(?:=\s*(0x[0-9a-fA-F]+|\d+))?\s*,?$", ln)
        if not m:
            sys.exit("gen-keytables: unparsed line: %r" % raw)
        variant, explicit = m.group(1), m.group(2)
        if explicit:
            val = int(explicit, 0)
        names = {variant.lower()} | {a.lower() for a in aliases} | {p.lower() for p in pending}
        pending = []
        for n in names:
            out[n] = val
        val += 1
    return out


def main():
    src_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    if not os.path.exists(src_path):
        sys.exit("gen-keytables: no upstream checkout at %s\n"
                 "           run ./pad build first" % src_path)
    src = open(src_path).read()

    keys = parse_enum(src, "WellKnownCode", 0x04)
    media = parse_enum(src, "MediaCode", 0)

    with open(OUT, "w") as f:
        f.write("# GENERATED by tools/gen-keytables.py from upstream\n")
        f.write("# src/keyboard/mod.rs (WellKnownCode / MediaCode). Do not edit by hand.\n")
        f.write("#\n")
        f.write("# %s\n" % src_path.replace(os.path.join(HERE, ".."), "<repo>"))
        f.write("#\n")
        f.write("# These tables are derived from upstream sources, MIT licensed:\n")
        f.write("#   Copyright 2023 Mikhail Trishchenkov\n")
        f.write("#   https://github.com/kriomant/ch57x-keyboard-tool\n")
        f.write("# See tests/golden/NOTICE for the full upstream licence notice.\n")
        f.write("\nKEYCODES = {\n")
        for n in sorted(keys):
            f.write("    %-22r: 0x%02x,\n" % (n, keys[n]))
        f.write("}\n\nMEDIACODES = {\n")
        for n in sorted(media):
            f.write("    %-22r: 0x%03x,\n" % (n, media[n]))
        f.write("}\n")

    print("wrote %s: %d key names, %d media names" % (OUT, len(keys), len(media)))


main()
