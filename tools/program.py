#!/usr/bin/env python3
"""
Program a CH57x macropad with no dependencies beyond Python 3 stdlib.

This is a self-contained reimplementation of the wire protocol documented in
AGENTS.md section 6, so the repo keeps working even if the upstream Rust
programmer (kriomant/ch57x-keyboard-tool) disappears.

    python3 tools/program.py config/media.yaml            # flash it
    python3 tools/program.py config/media.yaml --dry-run  # print bytes only

Writes 64-byte HID Output Reports to the pad's *interface 0* hidraw node, which
is the vendor programming channel. Needs write permission on that node
(see tools/install-udev.sh).

Supported macro syntax: single keys, modifier combos, comma-separated
sequences, media keys, and raw "<NNN>" HID usages. Mouse actions and {delay()}
options are deliberately NOT implemented - use the Rust tool for those.
"""
import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from keytables import KEYCODES, MEDIACODES      # generated by gen-keytables.py

# --------------------------------------------------------------------- config
#
# A parser for the YAML subset used by config/*.yaml: block mappings, block
# sequences, inline flow sequences, quoted/bare scalars, null, comments.
# Anything it cannot parse unambiguously is a hard error, never a guess.


class ConfigError(Exception):
    pass


def _strip_comment(s):
    out, quote, depth = [], None, 0
    for i, ch in enumerate(s):
        if quote:
            out.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in "\"'":
            quote = ch
            out.append(ch)
        elif ch == "[":
            depth += 1
            out.append(ch)
        elif ch == "]":
            depth -= 1
            out.append(ch)
        elif ch == "#" and depth == 0 and (i == 0 or s[i - 1] in " \t"):
            break
        else:
            out.append(ch)
    return "".join(out).strip()


def _split_top(s, sep):
    """Split on sep, ignoring separators inside quotes or brackets."""
    parts, cur, quote, depth = [], [], None, 0
    for ch in s:
        if quote:
            cur.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in "\"'":
            quote = ch
            cur.append(ch)
        elif ch == "[":
            depth += 1
            cur.append(ch)
        elif ch == "]":
            depth -= 1
            cur.append(ch)
        elif ch == sep and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur).strip())
    return parts


def _scalar(s):
    s = _strip_comment(s)
    if s == "" or s in ("null", "~"):
        return None
    if s.startswith("[") and s.endswith("]"):
        inner = s[1:-1].strip()
        return [] if not inner else [_scalar(x) for x in _split_top(inner, ",")]
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'":
        return s[1:-1]
    if any(c in s for c in ":#[]{}&*!|>%@`") and not s.startswith("<"):
        raise ConfigError("ambiguous scalar %r - quote it" % s)
    return s


def parse_yaml_subset(text):
    lines = []
    for raw in text.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if "\t" in raw[:len(raw) - len(raw.lstrip())]:
            raise ConfigError("tabs in indentation are not allowed")
        indent = len(raw) - len(raw.lstrip(" "))
        body = _strip_comment(raw.strip())
        if not body:
            continue
        # "- foo" / "- key: value" -> a bare "-" plus the payload indented by 2
        if body == "-" or body.startswith("- "):
            lines.append((indent, "-"))
            rest = body[2:].strip() if body.startswith("- ") else ""
            if rest:
                lines.append((indent + 2, rest))
        else:
            lines.append((indent, body))

    pos = [0]

    def looks_like_mapping(body):
        parts = _split_top(body, ":")
        return len(parts) >= 2 and parts[0].strip() != ""

    def node(indent):
        if pos[0] >= len(lines):
            raise ConfigError("unexpected end of file")
        ind, body = lines[pos[0]]
        if ind < indent:
            raise ConfigError("bad indentation at %r" % body)
        if body == "-":
            return seq(ind)
        if not looks_like_mapping(body):
            pos[0] += 1
            return _scalar(body)
        return mapping(ind)

    def seq(ind):
        items = []
        while pos[0] < len(lines) and lines[pos[0]][0] == ind and lines[pos[0]][1] == "-":
            pos[0] += 1
            if pos[0] < len(lines) and lines[pos[0]][0] > ind:
                items.append(node(lines[pos[0]][0]))
            else:
                items.append(None)
        return items

    def mapping(ind):
        out = {}
        while pos[0] < len(lines) and lines[pos[0]][0] == ind and \
                lines[pos[0]][1] != "-" and looks_like_mapping(lines[pos[0]][1]):
            body = lines[pos[0]][1]
            kv = _split_top(body, ":")
            if len(kv) < 2 or not kv[0]:
                raise ConfigError("expected 'key: value', got %r" % body)
            key = kv[0].strip()
            rest = ":".join(kv[1:]).strip()
            pos[0] += 1
            if rest:
                out[key] = _scalar(rest)
            elif pos[0] < len(lines) and lines[pos[0]][0] > ind:
                out[key] = node(lines[pos[0]][0])
            else:
                out[key] = None
        return out

    doc = node(0)
    if pos[0] != len(lines):
        raise ConfigError("unparsed input at %r" % lines[pos[0]][1])
    if not isinstance(doc, dict):
        raise ConfigError("top level must be a mapping")
    return doc


# ----------------------------------------------------------------- model
#
# Mirrors upstream src/config.rs so the same file works with both tools.

ORIENTATIONS = ("normal", "upsidedown", "clockwise", "counterclockwise")
MODELS = ("ch57x-1", "ch57x-2", "ch57x-3")


def _reorient_grid(orientation, rows, cols, data):
    if orientation == "normal":
        tr = lambda r, c, R, C: (r, c)
    elif orientation == "upsidedown":
        tr = lambda r, c, R, C: (R - r - 1, C - c - 1)
    elif orientation == "clockwise":
        tr = lambda r, c, R, C: (c, R - r - 1)
    else:
        tr = lambda r, c, R, C: (C - c - 1, r)
    out = []
    for i in range(rows * cols):
        r, c = tr(i // cols, i % cols, rows, cols)
        out.append(data[r][c])
    return out


def load_config(path):
    raw = parse_yaml_subset(open(path).read())
    for field in ("rows", "columns", "knobs", "layers"):
        if field not in raw:
            raise ConfigError("missing required field %r" % field)
    model = raw.get("model", "ch57x-1")
    if model not in MODELS:
        raise ConfigError("model must be one of %s, got %r" % (MODELS, model))
    if model != "ch57x-1":
        raise ConfigError("this tool only implements ch57x-1 (your pad); "
                          "use the Rust tool for %s" % model)
    orientation = raw.get("orientation", "normal")
    if orientation not in ORIENTATIONS:
        raise ConfigError("orientation must be one of %s" % (ORIENTATIONS,))
    rows, cols, knobs = int(raw["rows"]), int(raw["columns"]), int(raw["knobs"])
    if knobs > 3:
        raise ConfigError("more than 3 knobs is not supported by ch57x-1")

    layers = raw["layers"] or []
    if not 1 <= len(layers) <= 3:
        raise ConfigError("expected 1-3 layers, got %d" % len(layers))

    horizontal = orientation in ("normal", "upsidedown")
    orows, ocols = (rows, cols) if horizontal else (cols, rows)

    out = []
    for i, layer in enumerate(layers):
        if not isinstance(layer, dict):
            raise ConfigError("layer %d must be a mapping" % i)
        buttons = layer.get("buttons")
        knoblist = layer.get("knobs") or []
        if buttons is None or len(buttons) != orows:
            raise ConfigError("layer %d: expected %d button rows, got %s"
                              % (i, orows, len(buttons or [])))
        for row in buttons:
            if row is None or len(row) != ocols:
                raise ConfigError("layer %d: expected %d buttons per row" % (i, ocols))
        if len(knoblist) != knobs:
            raise ConfigError("layer %d: expected %d knobs, got %d" % (i, knobs, len(knoblist)))

        flat = _reorient_grid(orientation, rows, cols, buttons)
        krev = orientation in ("upsidedown", "clockwise")
        kl = list(knoblist)
        if krev:
            kl.reverse()
        out.append((flat, kl))
    return rows, cols, knobs, out


# ------------------------------------------------------------------- macros

MODIFIERS = {
    "ctrl": 0, "shift": 1, "alt": 2, "opt": 2, "win": 3, "cmd": 3,
    "rctrl": 4, "rshift": 5, "ralt": 6, "ropt": 6, "rwin": 7, "rcmd": 7,
}


class MacroError(Exception):
    pass


def parse_macro(text):
    """-> ('media', usage) | ('keys', [(modbits, usage_or_None), ...]) | None"""
    if text is None:
        return None
    text = str(text).strip()
    if text == "":
        return None
    if "(" in text or "{" in text:
        raise MacroError(
            "macro %r uses mouse actions or {delay()} options, which this "
            "tool does not implement - use ./pad with the Rust programmer" % text)

    parts = [p.strip() for p in _split_top(text, ",")]
    if any(p == "" for p in parts):
        raise MacroError("empty element in macro %r" % text)

    if len(parts) == 1 and parts[0].lower() in MEDIACODES:
        return ("media", MEDIACODES[parts[0].lower()])
    if any(p.lower() in MEDIACODES for p in parts):
        raise MacroError("media keys cannot be mixed with keys or modifiers: %r" % text)

    accords = []
    for part in parts:
        tokens = part.split("-")
        bits, idx = 0, 0
        # No key name collides with a modifier name, so consume greedily.
        while idx < len(tokens) and tokens[idx].lower() in MODIFIERS:
            bits |= 1 << MODIFIERS[tokens[idx].lower()]
            idx += 1
        key = "-".join(tokens[idx:])
        if key == "":
            accords.append((bits, None))          # modifier-only press
            continue
        m = re.fullmatch(r"<(\d+)>", key)
        if m:
            accords.append((bits, int(m.group(1)) & 0xFF))
        elif key.lower() in KEYCODES:
            accords.append((bits, KEYCODES[key.lower()]))
        else:
            raise MacroError("unknown key %r in %r (see: ./pad keys)" % (key, text))
    if len(accords) > 18:
        raise MacroError("macro %r: max 18 steps" % text)
    return ("keys", accords)


# ---------------------------------------------------------------- protocol

INIT = bytes(64)


def packet(msg):
    assert len(msg) <= 64, "message too long"
    return bytes(list(msg) + [0] * (64 - len(msg)))


def bind_messages(key_id, layer, macro):
    kind = 1 if macro[0] == "keys" else 2
    msg = [0x03, 0xFE, key_id, layer + 1, kind, 0, 0, 0, 0, 0]
    if macro[0] == "keys":
        accords = macro[1]
        modifier_only = len(accords) == 1 and accords[0][1] is None
        msg.append(0 if modifier_only else len(accords))
        for bits, code in accords:
            msg += [bits, code or 0]
    else:
        usage = macro[1]
        msg += [0, usage & 0xFF, (usage >> 8) & 0xFF, 0, 0, 0, 0]
    return [packet(msg),
            packet([0x03, 0xAA, 0xAA, 0, 0, 0, 0, 0, 0]),
            packet([0x03, 0xFD, 0xFE, 0xFF]),
            packet([0x03, 0xAA, 0xAA, 0, 0, 0, 0, 0, 0])]


def key_id_button(n):
    if n >= 15:
        raise ConfigError("button index %d out of range" % n)
    return n + 1


def key_id_knob(n, action):
    if n >= 3:
        raise ConfigError("knob index %d out of range" % n)
    return 16 + 3 * n + action          # action: 0=ccw 1=press 2=cw


def build(rows, cols, knobs, layers):
    """-> list of 64-byte packets"""
    # Upstream: 3x1 / 1x3 boards with one knob only honour modifiers on the
    # first key of a sequence.
    limited = (rows == 1 or cols == 1) and knobs == 1
    out = [INIT]
    for li, (flat, kl) in enumerate(layers):
        for bi, macro_text in enumerate(flat):
            macro = parse_macro(macro_text)
            if macro is None:
                continue
            if limited and macro[0] == "keys" and len(macro[1]) > 1:
                for bits, _ in macro[1][1:]:
                    if bits:
                        raise MacroError(
                            "3x1+1knob boards honour modifiers on the FIRST key "
                            "of a sequence only: %r" % macro_text)
            out += bind_messages(key_id_button(bi), li, macro)
        for ki, knob in enumerate(kl):
            if not isinstance(knob, dict):
                raise ConfigError("knob %d in layer %d must be a mapping" % (ki, li))
            for action, field in ((0, "ccw"), (1, "press"), (2, "cw")):
                macro = parse_macro(knob.get(field))
                if macro is None:
                    continue
                out += bind_messages(key_id_knob(ki, action), li, macro)
    return out


# ---------------------------------------------------------------- transport


def find_vendor_hidraw(vid, pid):
    """The programming channel is the pad's interface 0."""
    for h in sorted(glob.glob("/sys/class/hidraw/hidraw*")):
        try:
            ue = open(os.path.join(h, "device", "uevent")).read()
        except OSError:
            continue
        if ("%04X" % vid) not in ue or ("%04X" % pid) not in ue:
            continue
        try:
            iface = os.path.basename(os.path.realpath(os.path.join(h, "device", "..")))
        except OSError:
            continue
        if iface.endswith(":1.0"):
            return "/dev/" + os.path.basename(h)
    return None


def main():
    ap = argparse.ArgumentParser(description="program a CH57x macropad (stdlib only)")
    ap.add_argument("config")
    ap.add_argument("--dry-run", action="store_true",
                    help="print the byte stream instead of sending it")
    ap.add_argument("--dump", action="store_true",
                    help="like --dry-run but print all 64 bytes per packet (used by selftest)")
    ap.add_argument("--node", help="hidraw node of the vendor interface (auto-detected)")
    ap.add_argument("--vendor-id", type=lambda s: int(s, 0), default=0x514C)
    ap.add_argument("--product-id", type=lambda s: int(s, 0), default=0x8851)
    args = ap.parse_args()

    try:
        rows, cols, knobs, layers = load_config(args.config)
        packets = build(rows, cols, knobs, layers)
    except (ConfigError, MacroError) as e:
        sys.exit("config error: %s" % e)

    print("%s: %dx%d buttons, %d knob(s), %d layer(s) -> %d packets"
          % (args.config, rows, cols, knobs, len(layers), len(packets)))

    if args.dry_run or args.dump:
        width = 64 if args.dump else 24
        for i, p in enumerate(packets):
            print("%3d  %s" % (i, " ".join("%02x" % b for b in p[:width])))
        return

    node = args.node or find_vendor_hidraw(args.vendor_id, args.product_id)
    if not node:
        sys.exit("no vendor (interface 0) hidraw node for %04x:%04x - is the pad "
                 "plugged in? Try: ./pad status" % (args.vendor_id, args.product_id))
    try:
        fd = os.open(node, os.O_WRONLY)
    except OSError as e:
        sys.exit("cannot write %s: %s\n"
                 "       run ./pad udev once, or use the Docker fallback via ./pad"
                 % (node, e))
    try:
        for p in packets:
            if os.write(fd, p) != len(p):
                raise OSError("short write")
    finally:
        os.close(fd)
    print("sent %d packets to %s" % (len(packets), node))


if __name__ == "__main__":
    main()
